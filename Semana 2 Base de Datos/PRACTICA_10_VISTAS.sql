--4.MOSTRAR EL MEDICAMENTO MAS CARO Y MAS BARATO
CREATE OR REPLACE VIEW V_MEDICAMENTO_MIN_MAX AS
SELECT NOMBRE, PRECIO
FROM MEDICAMENTO
WHERE PRECIO = (SELECT MIN(PRECIO) FROM MEDICAMENTO)
   OR PRECIO = (SELECT MAX(PRECIO) FROM MEDICAMENTO);

SELECT * FROM V_MEDICAMENTO_MIN_MAX;

--5.UTILIZAR EL CASE PARA CLASIFICAR LOS MEDICAMENTOS 'ECONOMICO' 'MEDIO' 'CARO'


       CREATE OR REPLACE VIEW V_MED_CLASIF AS
       SELECT ID_MEDICAMENTO, NOMBRE, CONCENTRACION, VIA_ADMINISTRACION, LABORATORIO, PRECIO,
       CASE
          WHEN PRECIO <= 50 THEN ' PRECIO ECONOMICO'
          WHEN PRECIO BETWEEN 51 AND 150 THEN 'PRECIO MEDIO'
          ELSE 'PRECIO CARO'
