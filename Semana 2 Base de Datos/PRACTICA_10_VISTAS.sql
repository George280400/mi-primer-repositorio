--1.MOSTRAR EL TOTAL DE VENTAS POR MEDICAMENTO
 
          CREATE OR REPLACE VIEW V_VENTAS_TOTAL_MED AS
          SELECT M.NOMBRE, M.LABORATORIO, SUM(V.CANTIDAD) AS TOTAL_VENDIDO
          FROM MEDICAMENTO M
          LEFT JOIN VENTAS V ON M.ID_MEDICAMENTO = V.MEDICAMENTO_ID
          GROUP BY M.NOMBRE, M.LABORATORIO;
          
          SELECT * FROM V_VENTAS_TOTAL_MED;

--2.CALCULAR EL INGRESO TOTAL (CANTIDAD * PRECIO) GENERADO POR CADA MEDICAMENTO


CREATE OR REPLACE VIEW V_ING_TOTAL_MED AS
SELECT  M.ID_MEDICAMENTO, M.NOMBRE, SUM(V.CANTIDAD * M.PRECIO) AS INGRESO_TOTAL
FROM MEDICAMENTO M
LEFT JOIN VENTAS V ON  M.ID_MEDICAMENTO = V.MEDICAMENTO_ID
GROUP BY 
    M.ID_MEDICAMENTO, M.NOMBRE;

SELECT * FROM V_ING_TOTAL_MED;


--3.OBTENER EL MEDICAMENTO MAS VENDIDO


CREATE OR REPLACE VIEW V_MED_MAS_VEND AS
SELECT m.ID_MEDICAMENTO, m.NOMBRE, SUM(v.CANTIDAD) AS TOTAL_VENDIDO
FROM MEDICAMENTO m
INNER JOIN VENTAS v ON m.ID_MEDICAMENTO = v.MEDICAMENTO_ID
GROUP BY 
    m.ID_MEDICAMENTO, m.NOMBRE
ORDER BY 
TOTAL_VENDIDO DESC
FETCH FIRST 1 ROW ONLY;
    
    SELECT * FROM V_MED_MAS_VEND;


   
   
--4.MOSTRAR LOS MEDICAMENTOS QUE NO TENGAN VENTAS REALIZADAS

CREATE OR REPLACE VIEW V_MED_SIN_VENT AS

SELECT M.ID_MEDICAMENTO, M.NOMBRE, V.ID_VENTA
FROM MEDICAMENTO M
LEFT JOIN VENTAS V ON M.ID_MEDICAMENTO = V.MEDICAMENTO_ID
WHERE V.MEDICAMENTO_ID IS NULL
ORDER BY M.ID_MEDICAMENTO;

SELECT * FROM V_MED_SIN_VENT;


--5.MOSTRAR EL DETALLE CON EL NOMBRE DEL MEDICAMENTO LABORATORIO Y EL TOTAL VENDIDO CON UNCASE QUE INDIQUE 'POPULAR' 'MUY POPOLAR' 'NO PUPULAR'
CREATE OR REPLACE VIEW V_MED_POP AS
SELECT M.ID_MEDICAMENTO, M.NOMBRE, M.LABORATORIO, SUM(V.CANTIDAD) AS TOTAL_VENDIDO,
    CASE 
        WHEN SUM(V.CANTIDAD) >= 100 THEN 'MUY POPULAR'
        WHEN SUM(V.CANTIDAD) BETWEEN 50 AND 99 THEN 'POPULAR'
        ELSE 'NO POPULAR'
    END AS CLASIFICACION
FROM MEDICAMENTO M LEFT JOIN VENTAS V ON M.ID_MEDICAMENTO = V.MEDICAMENTO_ID
GROUP BY M.ID_MEDICAMENTO, M.NOMBRE, M.LABORATORIO
ORDER BY TOTAL_VENDIDO DESC;

SELECT * FROM V_MED_POP;

