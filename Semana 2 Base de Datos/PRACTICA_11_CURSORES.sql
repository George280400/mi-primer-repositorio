-- CREAR UN CURSOR QUE RECORRA TODOS LOS EMPLEADOS Y MUESTRE SU NOMBRE, DEPARTAMENTO Y PUESTO

CREATE OR REPLACE PROCEDURE PR_DETALLE_EMPLEADO IS
  -- PASO 1. DECLARAR EL CURSOR
    CURSOR EMPLEADO_INFO IS
    SELECT
        NOMBRE,
        DEPARTAMENTO,
        PUESTO
    FROM
        EMPLEADO;
     
     -- VARIABLES LOCALES
    LV_NOMBRE       EMPLEADO.NOMBRE%TYPE; -- SIRVE PARA GARANTIZAR QUE ESTA VARIABLE QUE ESTOY ASIGNANDO ES PARA EL NOMBRE DEL EMPLEADO
    LV_DEPARTAMENTO NVARCHAR2(20);
    LV_PUESTO       NVARCHAR2(20);
BEGIN
     -- PASO 2 ABRIR EL CURSOR
    OPEN EMPLEADO_INFO;
     -- PASO 3 RECUPERAR EL CURSOR
    LOOP
     -- POR CADA FILA RECORRIDA SE TOMEN LOS DATOS DEL CURSOR
        FETCH EMPLEADO_INFO INTO
            LV_NOMBRE,
            LV_DEPARTAMENTO,
            LV_PUESTO;
     -- CONDICION PARA SALIR CUANDO EL CURSOR YA NO TENGA REGISTROS
        EXIT WHEN EMPLEADO_INFO%NOTFOUND; -- NOT FOUND DEVUELVE UN TRUE SI EL ULTIMO FETCH NO OBTUVO FILA
     -- MOSTRAR LOS DATOS DEL CURSOR
        DBMS_OUTPUT.PUT_LINE('NOMBRE DEL EMPLEADO '
                             || LV_NOMBRE
                             || ' ES DEL DEPARTAMENTO '
                             || LV_DEPARTAMENTO
                             || ' Y TIENE UN PUESTO DE '
                             || LV_PUESTO);

    END LOOP;
     -- PASO 4 CERRAR EL CURSOR
    CLOSE EMPLEADO_INFO;
END;
/

BEGIN
    PR_DETALLE_EMPLEADO;
END;
