-- CREAR UN CURSOR QUE RECIBA COMO PARAMETRO EL NOMBRE DEL DEPARTAMENTO Y RETORNE TODOS LOS EMPLEADOS DEL DEPARTAMENTO

CREATE OR REPLACE PROCEDURE PR_EMPLEADOS_POR_DEPARTAMENTO (
    P_DEPARTAMENTO IN NVARCHAR2
) IS
  -- PASO 1: DECLARAR EL CURSOR
    CURSOR EMPLEADOS_DEPT IS
    SELECT
        NOMBRE,
        DEPARTAMENTO,
        PUESTO
    FROM
        EMPLEADO
    WHERE
        DEPARTAMENTO = P_DEPARTAMENTO;

  -- VARIABLES LOCALES
    LV_NOMBRE       EMPLEADO.NOMBRE%TYPE;
    LV_DEPARTAMENTO EMPLEADO.DEPARTAMENTO%TYPE;
    LV_PUESTO       EMPLEADO.PUESTO%TYPE;
BEGIN
  -- PASO 2: ABRIR EL CURSOR
    OPEN EMPLEADOS_DEPT;

  -- PASO 3: RECUPERAR LOS REGISTROS
    LOOP
        FETCH EMPLEADOS_DEPT INTO
            LV_NOMBRE,
            LV_DEPARTAMENTO,
            LV_PUESTO;
        EXIT WHEN EMPLEADOS_DEPT%NOTFOUND;

    -- MOSTRAR LOS DATOS
        DBMS_OUTPUT.PUT_LINE('NOMBRE: '
                             || LV_NOMBRE
                             || ', DEPARTAMENTO: '
                             || LV_DEPARTAMENTO
                             || ', PUESTO: '
                             || LV_PUESTO);

    END LOOP;

  -- PASO 4: CERRAR EL CURSOR
    CLOSE EMPLEADOS_DEPT;
END;
/


BEGIN
    PR_EMPLEADOS_POR_DEPARTAMENTO('TI');
END;
