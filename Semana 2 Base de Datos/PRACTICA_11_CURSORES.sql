-- CREAR UN CURSOR QUE MUESTRE LOS ALUMNOS QUE EN SU CARRERA TENGA LA PALABRA INGENIERIA
CREATE OR REPLACE PROCEDURE PR_ALUMNOS_INGENIERIA IS
  -- PASO 1: DECLARAR EL CURSOR
    CURSOR ALUMNOS_ING IS
    SELECT
        ID_ALUMNO,
        NOMBRE,
        CARRERA,
        SEMESTRE
    FROM
        ALUMNO
    WHERE
        UPPER(CARRERA) LIKE '%ING%';

  -- VARIABLES LOCALES
    LV_ID_ALUMNO ALUMNO.ID_ALUMNO%TYPE;
    LV_NOMBRE    ALUMNO.NOMBRE%TYPE;
    LV_CARRERA   ALUMNO.CARRERA%TYPE;
    LV_SEMESTRE  ALUMNO.SEMESTRE%TYPE;
BEGIN
  -- PASO 2: ABRIR EL CURSOR
    OPEN ALUMNOS_ING;

  -- PASO 3: RECUPERAR LOS REGISTROS
    LOOP
        FETCH ALUMNOS_ING INTO
            LV_ID_ALUMNO,
            LV_NOMBRE,
            LV_CARRERA,
            LV_SEMESTRE;
        EXIT WHEN ALUMNOS_ING%NOTFOUND;  -- SALE CUANDO NO HAY MÁS REGISTROS

    -- MOSTRAR LOS DATOS DEL CURSOR
        DBMS_OUTPUT.PUT_LINE('ID: '
                             || LV_ID_ALUMNO
                             || ', NOMBRE: '
                             || LV_NOMBRE
                             || ', CARRERA: '
                             || LV_CARRERA
                             || ', SEMESTRE: '
                             || LV_SEMESTRE);

    END LOOP;

  -- PASO 4: CERRAR EL CURSOR
    CLOSE ALUMNOS_ING;
END;
/

BEGIN
    PR_ALUMNOS_INGENIERIA;
END;
