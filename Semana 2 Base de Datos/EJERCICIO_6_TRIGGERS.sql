CREATE OR REPLACE TRIGGER TR_D_CELULAR
AFTER DELETE ON CELULAR
FOR EACH ROW
DECLARE
    LV_ID_BIT   NUMBER;
    LV_USUARIO  NVARCHAR2(100);
    LV_FECHA    DATE;
BEGIN
    -- Recuperar la fecha del sistema
    SELECT SYSDATE INTO LV_FECHA FROM DUAL;

    -- Recuperar el usuario
    SELECT USER INTO LV_USUARIO FROM DUAL;

    -- Obtener un ID válido para la bitácora
    SELECT NVL(MAX(ID_BIT),0) + 1 INTO LV_ID_BIT FROM BIT_CEL;

    -- Insertar registro en bitácora con valores eliminados
    INSERT INTO BIT_CEL (ID_BIT, ID_CELULAR, MARCA, MODELO, PROCESADOR, CAPACIDAD, COLOR, PRECIO,MARCA_OLD, MODELO_OLD, PROCESADOR_OLD, CAPACIDAD_OLD, COLOR_OLD, PRECIO_OLD,USUARIO, FECHA_MOV, MOVIMIENTO) 
    VALUES (
        LV_ID_BIT,
        :OLD.ID_CELULAR,    NULL,NULL,NULL,NULL,NULL,NULL,:OLD.MARCA,:OLD.MODELO,:OLD.PROCESADOR,:OLD.CAPACIDAD,:OLD.COLOR,:OLD.PRECIO,LV_USUARIO,LV_FECHA,'DELETE');
END TR_D_CELULAR;
