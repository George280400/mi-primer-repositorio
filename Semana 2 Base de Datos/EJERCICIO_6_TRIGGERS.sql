CREATE OR REPLACE TRIGGER TR_U_CELULAR
AFTER UPDATE ON CELULAR
FOR EACH ROW
DECLARE
    LV_ID_BIT   NUMBER;
    LV_USUARIO  NVARCHAR2(100);
    LV_FECHA    DATE;
BEGIN

    --COMO RECUPERAR LA FECHA DEL SISTEMA
    SELECT SYSDATE INTO LV_FECHA FROM DUAL;

    --RECUPERAR EL USUARIO
    SELECT USER INTO LV_USUARIO FROM DUAL;

    --OBTENER UN ID VALIDO PARA MI TABLA BITACORA
    SELECT NVL(MAX(ID_BIT),0) + 1 INTO LV_ID_BIT FROM BIT_CEL;

    -- Insertar registro en bitácora con valores nuevos y viejos
    INSERT INTO BIT_CEL (ID_BIT, ID_CELULAR, MARCA, MODELO, PROCESADOR, CAPACIDAD, COLOR, PRECIO,MARCA_OLD, MODELO_OLD, PROCESADOR_OLD, CAPACIDAD_OLD, COLOR_OLD, PRECIO_OLD,USUARIO, FECHA_MOV, MOVIMIENTO)
    VALUES (LV_ID_BIT,:NEW.ID_CELULAR,:NEW.MARCA,:NEW.MODELO,:NEW.PROCESADOR,:NEW.CAPACIDAD,:NEW.COLOR,:NEW.PRECIO,:OLD.MARCA,:OLD.MODELO,:OLD.PROCESADOR,:OLD.CAPACIDAD,:OLD.COLOR,:OLD.PRECIO,LV_USUARIO,LV_FECHA,'UPDATE');

END TR_U_CELULAR;
/


