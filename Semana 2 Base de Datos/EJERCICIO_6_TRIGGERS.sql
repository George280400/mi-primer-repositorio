--TRIGGER PARA UNA AUDITORIA SIMPLE
--CREAR UNA ENTIDAD
CREATE TABLE CELULAR(
ID_CELULAR NUMBER,
MARCA NVARCHAR2(100),
MODELO NVARCHAR2(100),
PROCESADOR NVARCHAR2(100),
CAPACIDAD NVARCHAR2(100),
COLOR NVARCHAR2(100),
PRECIO NUMBER,
CONSTRAINT CEL_PK PRIMARY KEY(ID_CELULAR)
);

--CREAR UNA ENTIDAD BITACORA QUE REGISTRARA CADA EVENTO OCURRIDO EN LA TABLA CELULAR

CREATE TABLE BIT_CEL(
ID_BIT NUMBER,

--VALORES NUEVOS :NEW
ID_CELULAR NUMBER,
MARCA NVARCHAR2(100),
MODELO NVARCHAR2(100),
PROCESADOR NVARCHAR2(100),
CAPACIDAD NVARCHAR2(100),
COLOR NVARCHAR2(100),
PRECIO NUMBER,

--VALORES VIEJOS: OLD
MARCA_OLD NVARCHAR2(100),
MODELO_OLD NVARCHAR2(100),
PROCESADOR_OLD NVARCHAR2(100),
CAPACIDAD_OLD NVARCHAR2(100),
COLOR_OLD NVARCHAR2(100),
PRECIO_OLD NUMBER,

--CAMPOS DE CONTROL
USUARIO NVARCHAR2(100),
FECHA_MOV DATE,
MOVIMIENTO NVARCHAR2(100),
CONSTRAINT BIT_CEL_PK PRIMARY KEY(ID_BIT)
);

--TRIGGER
CREATE OR REPLACE TRIGGER TR_I_CELULAR
AFTER INSERT ON CELULAR
FOR EACH ROW 
DECLARE
    LV_ID_BIT NUMBER;
    LV_USUARIO NVARCHAR2(100);
    LV_FECHA DATE;
BEGIN
        --COMO RECUPERAR LA FECHA DEL SISTEMA
        SELECT SYSDATE INTO LV_FECHA FROM DUAL;
        
        --RECUPERAR EL USUARIO
        SELECT USER INTO LV_USUARIO FROM DUAL;
        
        --OBTENER UN ID VALIDO PARA MI TABLA BITACORA
        SELECT NVL(MAX(ID_BIT),0) + 1 INTO LV_ID_BIT FROM BIT_CEL;
        
        INSERT INTO BIT_CEL(ID_BIT,ID_CELULAR,MARCA,MODELO,PROCESADOR,CAPACIDAD,COLOR,PRECIO,MARCA_OLD,MODELO_OLD,PROCESADOR_OLD,CAPACIDAD_OLD,COLOR_OLD,PRECIO_OLD,USUARIO,FECHA_MOV,MOVIMIENTO)
        VALUES(LV_ID_BIT,:NEW.ID_CELULAR,:NEW.MARCA,:NEW.MODELO,:NEW.PROCESADOR,:NEW.CAPACIDAD,:NEW.COLOR,:NEW.PRECIO,NULL,NULL,NULL,NULL,NULL,0,LV_USUARIO,LV_FECHA,'INSERT');
        END TR_I_CELULAR;
/

