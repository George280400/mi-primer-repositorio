--SE USAN MUCHO CUANDO QUIERES REUTILIZAR CODIGO QUE SIEMPRE RETORNA UN RESULTADO (A DIFERENCIA DE UN PROCEDIMIENTO ALMACENADO QUE NO NECESAREAMENTE RETORNA UN VALOR)

--FUNCION QUE SUMA LOS NUMEROS
CREATE OR REPLACE FUNCTION SUMA(A NUMBER, B NUMBER)
RETURN NUMBER IS 
    RESULTADO NUMBER; --DECLARACION DE VARIABLES LOCALES
    BEGIN
    --LOGICA DE LA FUNCION
    RESULTADO := A + B;
    RETURN RESULTADO; --OBLIGATORIA POR QUE UNA FUNCION SIEMORE RETORNA UN VALOR
    
END;
/

--LLAMAR A LA FUNCION UNA VEZ COMPILADA
 SELECT SUMA(10,5) FROM DUAL;
 
 --INVOCACION MEDIANTE UN BLOQUE ANONIMO
 BEGIN DBMS_OUTPUT.PUT_LINE('EL RESULATADO DE LA SUMA ES: ' || SUMA(2, 6));
 END;
