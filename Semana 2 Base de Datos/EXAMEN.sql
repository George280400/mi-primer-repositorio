--CREACION DE TABLAS
CREATE TABLE equipos (
    NOMBRE      VARCHAR2(20) PRIMARY KEY,
    CIUDAD      VARCHAR2(20),
    CONFERENCIA VARCHAR2(4),
    DIVISION    VARCHAR2(9)
);

CREATE TABLE jugadores (
    CODIGO       NUMBER PRIMARY KEY,
    NOMBRE       VARCHAR2(30),
    PROCEDENCIA  VARCHAR2(20),
    ALTURA       VARCHAR2(4),
    PESO         NUMBER,
    POSICION     VARCHAR2(5),
    NOMBRE_EQUIPO VARCHAR2(20),
    CONSTRAINT FK_JUGADORES_EQUIPO FOREIGN KEY (NOMBRE_EQUIPO)
        REFERENCES equipos(NOMBRE)
);

CREATE TABLE partidos (
    CODIGO           NUMBER PRIMARY KEY,
    EQUIPO_LOCAL     VARCHAR2(20),
    EQUIPO_VISITANTE VARCHAR2(20),
    PUNTOS_LOCAL     NUMBER,
    PUNTOS_VISITANTE NUMBER,
    TEMPORADA        VARCHAR2(5),
    CONSTRAINT FK_PARTIDOS_LOCAL FOREIGN KEY (EQUIPO_LOCAL)
        REFERENCES equipos(NOMBRE),
    CONSTRAINT FK_PARTIDOS_VISITANTE FOREIGN KEY (EQUIPO_VISITANTE)
        REFERENCES equipos(NOMBRE)
);

CREATE TABLE estadisticas (
    TEMPORADA           VARCHAR2(5),
    JUGADOR             NUMBER,
    PUNTOS_POR_PARTIDO  FLOAT(126),
    ASISTENCIAS_POR_PARTIDO FLOAT(126),
    TAPONES_POR_PARTIDO FLOAT(126),
    REBOTES_POR_PARTIDO FLOAT(126),
    CONSTRAINT ESTADISTICAS_PK PRIMARY KEY (TEMPORADA, JUGADOR),
    CONSTRAINT FK_ESTADISTICAS_JUGADOR FOREIGN KEY (JUGADOR)
        REFERENCES jugadores(CODIGO)
);



