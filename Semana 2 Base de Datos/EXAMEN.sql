--13.	Mostrar el partido o partidos (equipo_local, equipo_visitante y diferencia) con mayor diferencia de puntos. (CREAR UNA VIEW)
CREATE OR REPLACE VIEW V_PARTIDOS_MAYOR_DIFERENCIA  AS
SELECT P.EQUIPO_LOCAL, P.EQUIPO_VISITANTE,
       ABS(P.PUNTOS_LOCAL - P.PUNTOS_VISITANTE) AS DIFERENCIA
FROM PARTIDOS P
WHERE ABS(P.PUNTOS_LOCAL - P.PUNTOS_VISITANTE) = (
    SELECT MAX(ABS(P2.PUNTOS_LOCAL - P2.PUNTOS_VISITANTE))
    FROM PARTIDOS P2
);

SELECT * FROM V_PARTIDOS_MAYOR_DIFERENCIA;


--14.	Mostrar la media de puntos en partidos de los equipos de la división Pacific. (CREAR UNA VIEW)
CREATE OR REPLACE VIEW V_MEDIA_PUNTOS_PACIFIC AS
SELECT AVG(P.PUNTOS_LOCAL + P.PUNTOS_VISITANTE) AS MEDIA_PUNTOS
FROM PARTIDOS P
INNER JOIN EQUIPOS E1 ON P.EQUIPO_LOCAL = E1.NOMBRE
INNER JOIN EQUIPOS E2 ON P.EQUIPO_VISITANTE = E2.NOMBRE
WHERE E1.DIVISION = 'Pacific'
   OR E2.DIVISION = 'Pacific';
   
SELECT * FROM V_MEDIA_PUNTOS_PACIFIC;

--15.	Mostrar los puntos de cada equipo en los partidos, tanto de local como de visitante. Usa una vista (CREAR UNA VIEW)
CREATE OR REPLACE VIEW V_PUNTOS_EQUIPOS AS
SELECT P.CODIGO AS PARTIDO,
       P.EQUIPO_LOCAL AS EQUIPO_LOCAL,
       P.PUNTOS_LOCAL AS PUNTOS_LOCAL,
       P.EQUIPO_VISITANTE AS EQUIPO_VISITANTE,
       P.PUNTOS_VISITANTE AS PUNTOS_VISITANTE
FROM PARTIDOS P
ORDER BY PARTIDO ASC;

SELECT * FROM V_PUNTOS_EQUIPOS;

